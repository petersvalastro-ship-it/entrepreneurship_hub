/** Key used to spot duplicates: case, punctuation, "(…)" asides and a plural "s" are ignored. */
export function glossaryKey(term: string): string {
  return term.replace(/\(.*?\)/g, '').toLowerCase().replace(/[^a-z0-9 ]/g, '').trim().replace(/\s+/g, ' ').replace(/s$/, '');
}

/** A–Z by term, ignoring case; terms starting with a number come first. */
export function sortGlossary<T extends { term: string }>(list: T[]): T[] {
  return [...list].sort((a, b) => a.term.localeCompare(b.term, 'en', { sensitivity: 'base', numeric: true }));
}

/** Letter heading a term is filed under ("#" for numbers). */
export function glossaryLetter(term: string): string {
  const c = term.trim().charAt(0).toUpperCase();
  return /[A-Z]/.test(c) ? c : '#';
}

